-- CRM MySQL migration: move the CRM data of Wedding gifts leads from source 'spin' to 'wedding_gifts'.
-- Do not run against the read-only Spin workflow PostgreSQL database.
--
-- Wedding gifts leads are spin_lead rows whose additional_details.otherWeddingServices names
-- "Wedding Gifts & Return Gifts" (case-insensitive, also inside combinations). They stay in the
-- workflow table; only the CRM rows keyed by them change source:
--   crm_lead_meta, crm_hot_leads, crm_lead_activity, crm_notifications (source + lead_key)
-- crm_notification_reads has no source (it follows notification ids): untouched.
-- Manual assignments (crm_lead_meta.vendor_id) are kept as they are.
-- No schema change: CRM-added gift leads stay in crm_spin_leads and are told apart by the same rule.
--
-- Steps (one session: the key list is a TEMPORARY table):
--   0. Regenerate the workflow keys right before applying (read-only):
--        venv\Scripts\python scripts\wedding_gifts_keys.py --update migrations\2026-11-20_wedding_gifts_source.sql
--   1. Keys        (run)
--   2. Preview     (run, read the counts; the conflict checks must be 0)
--   3. Apply       (run)
--   R. Rollback    (only to undo; see the section at the end)
--
-- Numbers when this file was written (2026-11-20, read-only counts): 144 workflow keys (143 an hour
-- earlier: new gift leads keep arriving, hence step 0), 0 CRM-added gift leads; rows to change:
-- crm_lead_meta 1 (lead 3715, manual Phodeo, kept), crm_hot_leads 0, crm_lead_activity 0,
-- crm_notifications 0.

