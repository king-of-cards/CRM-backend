-- CRM-added gift leads (crm-<id>), same rule as the app
INSERT IGNORE INTO tmp_wedding_gift_keys (lead_key)
SELECT CONCAT('crm-', id)
FROM crm_spin_leads
WHERE LOWER(JSON_UNQUOTE(JSON_EXTRACT(additional_details, '$.otherWeddingServices')))
      LIKE '%wedding gifts & return gifts%';

-- ── 2. Preview (read only) ─────────────────────────────────────────────
-- MySQL can't open a TEMPORARY table twice in one statement, so one SELECT per table.
SELECT COUNT(*) AS keys_total FROM tmp_wedding_gift_keys;
SELECT 'crm_lead_meta' AS tbl, COUNT(*) AS rows_to_move
FROM crm_lead_meta m JOIN tmp_wedding_gift_keys k ON k.lead_key = m.lead_key WHERE m.source = 'spin';
SELECT 'crm_hot_leads' AS tbl, COUNT(*) AS rows_to_move
FROM crm_hot_leads h JOIN tmp_wedding_gift_keys k ON k.lead_key = h.lead_key WHERE h.source = 'spin';
SELECT 'crm_lead_activity' AS tbl, COUNT(*) AS rows_to_move
FROM crm_lead_activity a JOIN tmp_wedding_gift_keys k ON k.lead_key = a.lead_key WHERE a.source = 'spin';
SELECT 'crm_notifications' AS tbl, COUNT(*) AS rows_to_move
FROM crm_notifications n JOIN tmp_wedding_gift_keys k ON k.lead_key = n.lead_key WHERE n.source = 'spin';
-- The rows themselves (CRM details of the moving leads)
SELECT m.id, m.lead_key, m.vendor_id, m.auto_assign, m.update_status, m.follow_up_date
FROM crm_lead_meta m JOIN tmp_wedding_gift_keys k ON k.lead_key = m.lead_key WHERE m.source = 'spin';
-- Conflict checks: both must be 0 (unique (source, lead_key) on these tables)
SELECT 'crm_lead_meta conflicts' AS chk, COUNT(*) AS n
FROM crm_lead_meta m JOIN tmp_wedding_gift_keys k ON k.lead_key = m.lead_key WHERE m.source = 'wedding_gifts';
SELECT 'crm_hot_leads conflicts' AS chk, COUNT(*) AS n
FROM crm_hot_leads h JOIN tmp_wedding_gift_keys k ON k.lead_key = h.lead_key WHERE h.source = 'wedding_gifts';

-- ── 3. Apply ───────────────────────────────────────────────────────────
START TRANSACTION;
UPDATE crm_lead_meta m JOIN tmp_wedding_gift_keys k ON k.lead_key = m.lead_key
SET m.source = 'wedding_gifts' WHERE m.source = 'spin';
UPDATE crm_hot_leads h JOIN tmp_wedding_gift_keys k ON k.lead_key = h.lead_key
SET h.source = 'wedding_gifts' WHERE h.source = 'spin';
UPDATE crm_lead_activity a JOIN tmp_wedding_gift_keys k ON k.lead_key = a.lead_key
SET a.source = 'wedding_gifts' WHERE a.source = 'spin';
UPDATE crm_notifications n JOIN tmp_wedding_gift_keys k ON k.lead_key = n.lead_key
SET n.source = 'wedding_gifts' WHERE n.source = 'spin';
COMMIT;

-- Check after: 0 rows of the moved keys left under 'spin'
SELECT COUNT(*) AS spin_rows_left
FROM crm_lead_meta m JOIN tmp_wedding_gift_keys k ON k.lead_key = m.lead_key WHERE m.source = 'spin';

DROP TEMPORARY TABLE IF EXISTS tmp_wedding_gift_keys;

